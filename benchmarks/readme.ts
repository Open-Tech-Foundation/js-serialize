// Renders benchmarks/results.json into README.md, between the
// <!-- bench:start --> and <!-- bench:end --> markers. Run: tsr bench:readme
import * as fs from "runtime:fs";

const at = (rel: string): string => new URL(rel, import.meta.url).pathname;
const START = "<!-- bench:start -->";
const END = "<!-- bench:end -->";

type Row<T> = { lib: string } & T;
interface Results {
  meta: {
    generatedAt: string;
    runtime: string;
    cpu: string | null;
    threads: number;
    package: string;
    versions: Record<string, string>;
    regenerate: string;
  };
  libraries: string[];
  fidelity: { cases: string[]; rows: Row<{ cells: string[]; score: number }>[] };
  malformed: { cases: string[]; rows: Row<{ cells: string[] }>[] };
  size: { cases: string[]; rows: Row<{ bytes: (number | null)[] }>[] };
  speed: {
    scenario: string;
    ops: { op: string; rows: Row<{ opsPerSec: number | null; rme: number | null }>[] }[];
  }[];
}

const r: Results = JSON.parse(await fs.file(at("results.json")).text());
const ours = r.meta.package;
const head = (name: string) => (name === ours ? `**${name}**` : name);
const table = (header: string[], rows: string[][]): string =>
  [header, header.map(() => "---"), ...rows].map((cells) => `| ${cells.join(" | ")} |`).join("\n");
const num = (n: number) => n.toLocaleString("en-US");

const FIDELITY: Record<string, string> = { pass: "✅", fail: "❌", throws: "💥" };

const fidelity = table(
  ["Value", ...r.libraries.map(head)],
  [
    ...r.fidelity.cases.map((label, i) => [
      label,
      ...r.fidelity.rows.map((row) => FIDELITY[row.cells[i]]),
    ]),
    ["**Score**", ...r.fidelity.rows.map((row) => `**${row.score}/${r.fidelity.cases.length}**`)],
  ],
);

const malformed = table(
  ["`parse(...)` input", ...r.libraries.map(head)],
  r.malformed.cases.map((label, i) => [
    label,
    ...r.malformed.rows.map((row) =>
      row.cells[i] === "throws"
        ? "throws"
        : `⚠️ ${row.cells[i].replace(/^returns /, "returns `")}\``,
    ),
  ]),
);

const size = table(
  ["Value", ...r.libraries.map(head)],
  r.size.cases.map((label, i) => {
    const vals = r.size.rows.map((row) => row.bytes[i]);
    const best = Math.min(...vals.filter((v): v is number => v != null));
    return [label, ...vals.map((v) => (v == null ? "—" : v === best ? `**${v}**` : String(v)))];
  }),
);

const speed = r.speed
  .map(({ scenario, ops }) => {
    const libsHere = ops[0].rows.map((row) => row.lib);
    const best = ops.map((o) => Math.max(...o.rows.map((row) => row.opsPerSec ?? 0)));
    const rows = libsHere.map((lib, li) => [
      head(lib),
      ...ops.map((o, oi) => {
        const v = o.rows[li].opsPerSec;
        if (v == null) return "—";
        return v === best[oi] ? `**${num(v)}**` : num(v);
      }),
    ]);
    return `**${scenario}** (ops/sec, higher is better)\n\n${table(
      ["Library", ...ops.map((o) => `\`${o.op}\``)],
      rows,
    )}`;
  })
  .join("\n\n");

const versions = Object.entries(r.meta.versions)
  .filter(([name]) => name !== ours)
  .map(([name, v]) => `${name} ${v}`)
  .join(", ");
const machine = [r.meta.cpu, `${r.meta.threads} threads`].filter(Boolean).join(", ");

const section = `${START}
<!-- Generated by \`${r.meta.regenerate}\` from benchmarks/results.json — do not edit by hand. -->

Measured ${r.meta.generatedAt} on ${r.meta.runtime} (${machine}) against ${versions}.

#### Round-trip fidelity

Each value goes through \`stringify\` then \`parse\` and must come back with the same
type, value, keys and identity. ✅ exact · ❌ different value or type · 💥 throws.

${fidelity}

#### Malformed input

What \`parse\` does with valid JSON that is not its own format. Throwing is the safe answer;
a quiet \`undefined\` reaches application code as if it were data.

${malformed}

#### Wire size

UTF-8 bytes of the output; smallest in bold.

${size}

#### Speed

${speed}
${END}`;

const readmePath = at("../README.md");
const readme = await fs.file(readmePath).text();
const from = readme.indexOf(START);
const to = readme.indexOf(END);
if (from < 0 || to < from) throw new Error(`README.md has no ${START} … ${END} section`);
await fs.write(readmePath, readme.slice(0, from) + section + readme.slice(to + END.length));
console.log("README.md benchmark section updated");
